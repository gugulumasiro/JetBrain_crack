#!/usr/bin/env bash
# JetBrains 一键激活（Linux / macOS）— 离线版，全程不启动服务器
#
# 一条命令完成全部激活流程：
#   1. 解压脚本内嵌的 12 款产品预生成许可证（目标机器无需 Python）
#   2. 激活本机 JetBrains IDE（离线执行 scripts/Linux-macOS/activate.sh：
#      ja-netfilter 资源从仓库本地复制，许可证使用内嵌的预生成许可证）

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
SELF="$(cd "$SCRIPT_DIR" && pwd)/$(basename "$0")"

log() { printf '\033[0;36m%s\033[0m\n' "$1"; }
ok()  { printf '\033[0;32m%s\033[0m\n' "$1"; }
err() { printf '\033[0;31m%s\033[0m\n' "$1"; }

log '========================================'
log '  JetBrains 一键激活（Linux / macOS）'
log '  离线模式 · 不启动服务器'
log '========================================'

# ---------- 1. 解压内嵌许可证 ----------
log '[1/2] 解压脚本内嵌的预生成许可证...'
for cmd in base64 unzip; do
    if ! command -v "$cmd" >/dev/null 2>&1; then
        err "[错误] 未找到 $cmd。离线激活需要 base64 与 unzip。"
        exit 1
    fi
done
TMPDIR="$(mktemp -d)" || { err '[错误] 创建临时目录失败。'; exit 1; }
trap 'rm -rf "$TMPDIR"' EXIT
m_begin='__JB_OFFLINE_'
begin="${m_begin}PACK__"
end="${m_begin}END__"
sed -n "/^${begin}$/,/^${end}$/p" "$SELF" | sed '1d;$d' > "$TMPDIR/pack.b64"
if base64 --decode < "$TMPDIR/pack.b64" > "$TMPDIR/pack.zip" 2>/dev/null; then
    :
elif base64 -D < "$TMPDIR/pack.b64" > "$TMPDIR/pack.zip" 2>/dev/null; then
    :
else
    err '[错误] 解压内嵌许可证失败（载荷无效，可能未执行内嵌步骤）。'
    exit 1
fi
unzip -q "$TMPDIR/pack.zip" -d "$TMPDIR/licenses" || {
    err '[错误] 解压内嵌许可证失败。'
    exit 1
}
ok '[1/2] 许可证就绪。'

# ---------- 2. 激活（离线执行，复制临时副本以免 activate.sh 自删仓库文件） ----------
log ''
log '开始激活。请按提示选择产品。'
TMP_SCRIPT="$(mktemp /tmp/jb_activate.XXXXXX.sh)" || { err '[错误] 创建临时激活脚本失败。'; exit 1; }
cp "$SCRIPT_DIR/activate.sh" "$TMP_SCRIPT" || {
    err '[错误] 复制激活脚本失败。'
    exit 1
}
OFFLINE_RESOURCES_DIR="$REPO_ROOT/ja-netfilter" \
OFFLINE_LICENSES_DIR="$TMPDIR/licenses" \
    bash "$TMP_SCRIPT"
rm -f "$TMP_SCRIPT"
ok ''
ok '激活流程已结束。'

exit 0

